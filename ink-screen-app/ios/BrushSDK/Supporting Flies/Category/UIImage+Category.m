    //    Get the new image from the context
    UIImage *newImage = UIGraphicsGetImageFromCurrentImageContext();
    //    End the context
    //    UIGraphicsEndPDFContext();
    UIGraphicsEndImageContext();
    //    Return the new image;
    
    return newImage;
}

