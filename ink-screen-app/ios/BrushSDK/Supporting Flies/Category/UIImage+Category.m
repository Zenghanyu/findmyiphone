+ (void) saveImage:(UIImage *)tempImage WithName:(NSString *)imageName
{
    NSString *strextension = [imageName pathExtension];
    NSData *imageData = nil;
    if ([strextension isEqualToString:@"png"])
    {
        imageData = UIImagePNGRepresentation(tempImage);
    }
    else if ([strextension isEqualToString:@"jpg"])
    {
        imageData = UIImageJPEGRepresentation(tempImage, 1.0);
    }
    else
    {
        imageData = UIImagePNGRepresentation(tempImage);
    }
    NSString *strPath = [NSString stringWithFormat:@"%@/Caches", [NSSearchPathForDirectoriesInDomains(NSLibraryDirectory, NSUserDomainMask, YES) objectAtIndex:0]];
    strPath = [strPath stringByAppendingPathComponent:imageName];
    dispatch_async(dispatch_get_global_queue(DISPATCH_QUEUE_PRIORITY_DEFAULT, 0), ^{
        [imageData writeToFile:strPath atomically:NO];
    });
}

static void addRoundedRectToPath(CGContextRef context, CGRect rect, float ovalWidth,
                                 float ovalHeight)
{
    float fw, fh;
    
    if (ovalWidth == 0 || ovalHeight == 0)
    {
        CGContextAddRect(context, rect);
        return;
    }
    
    CGContextSaveGState(context);
    CGContextTranslateCTM(context, CGRectGetMinX(rect), CGRectGetMinY(rect));
    CGContextScaleCTM(context, ovalWidth, ovalHeight);
    fw = CGRectGetWidth(rect) / ovalWidth;
    fh = CGRectGetHeight(rect) / ovalHeight;
    
    CGContextMoveToPoint(context, fw, fh/2);  // Start at lower right corner
    CGContextAddArcToPoint(context, fw, fh, fw/2, fh, 1);  // Top right corner
    CGContextAddArcToPoint(context, 0, fh, 0, fh/2, 1); // Top left corner
    CGContextAddArcToPoint(context, 0, 0, fw/2, 0, 1); // Lower left corner
    CGContextAddArcToPoint(context, fw, 0, fw, fh/2, 1); // Back to lower right
    
    CGContextClosePath(context);
    CGContextRestoreGState(context);
}

